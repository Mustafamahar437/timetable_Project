"""
ui/pages/syntax_view.py
=======================
Phase 2: Syntax Analysis Visualization page.
Displays Concrete Syntax Tree (CST) / Parse Tree, grammar rules, and syntax validation status.
"""

from __future__ import annotations
import streamlit as st
from ui import theme


def render(session_state):
    theme.page_header("🌳 Phase 2: Syntax Analysis", "Inspect the Parse Tree generated by the Lark Context-Free Grammar (CFG) parser.")

    parse_tree = session_state.get("parse_tree")
    parse_tree_repr = session_state.get("parse_tree_repr", "")

    if parse_tree is None:
        st.info("No parse tree generated yet. Run the Parser from the **Rule Editor** page.")
        return

    st.success("✅ Grammar Verification Passed: All rules conform to the TCS EBNF Grammar.")

    tab_tree, tab_grammar = st.tabs(["🌳 Hierarchical Parse Tree", "📜 TCS EBNF Grammar Specification"])

    with tab_tree:
        st.markdown("#### Concrete Syntax Tree (CST):")
        st.code(parse_tree_repr if parse_tree_repr else str(parse_tree), language="text")

    with tab_grammar:
        st.markdown(
            """
            ```ebnf
            // TCS Grammar in Lark EBNF format
            start: statement* -> program
            statement: rule_decl SEMICOLON

            rule_decl: "RULE" ( no_room_clash
                             | no_teacher_clash
                             | teacher_not_available
                             | course_room
                             | course_teacher
                             | course_duration
                             | course_students
                             | course_days_per_week
                             | room_capacity
                             | course_preferred_time
                             | course_preferred_day
                             | group_no_clash )

            no_room_clash: "NO_ROOM_CLASH"
            no_teacher_clash: "NO_TEACHER_CLASH"
            teacher_not_available: IDENTIFIER "NOT_AVAILABLE" DAY TIME
            course_room: IDENTIFIER "ROOM" IDENTIFIER
            course_teacher: IDENTIFIER "TEACHER" IDENTIFIER
            course_duration: IDENTIFIER "DURATION" DURATION_VAL
            course_students: IDENTIFIER "STUDENTS" NUMBER
            course_days_per_week: IDENTIFIER "DAYS_PER_WEEK" NUMBER
            room_capacity: IDENTIFIER "CAPACITY" NUMBER
            course_preferred_time: IDENTIFIER "PREFERRED_TIME" TIME
            course_preferred_day: IDENTIFIER "PREFERRED_DAY" DAY
            group_no_clash: IDENTIFIER "NO_CLASH"
            ```
            """
        )
