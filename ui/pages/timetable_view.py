"""
ui/pages/timetable_view.py
==========================
Phase 6 & Output: Generated Timetable View page.
Renders timetable in interactive grid, faculty view, room view, and provides CSV / PDF export.
"""

from __future__ import annotations
import io
import streamlit as st
from ui import theme
import pandas as pd

try:
    from fpdf import FPDF
    FPDF_AVAILABLE = True
except ImportError:
    FPDF_AVAILABLE = False


def render(session_state, db_manager):
    theme.page_header("📅 Phase 6 & Output: University Timetable", "Clash-free university timetable generated via Google OR-Tools CP-SAT solver.")

    solver_res = session_state.get("solver_result")

    # If solver hasn't been run this session, try reading from database
    entries = []
    if solver_res and solver_res.timetable:
        entries = [e.to_dict() for e in solver_res.timetable]
    else:
        entries = db_manager.get_timetable_entries()

    if not entries:
        st.info("No timetable generated yet. Navigate to **Rule Editor** and click **🚀 Run Full Compilation Pipeline**.")
        return

    st.success(f"Generated schedule contains **{len(entries)} scheduled course sessions**.")

    tab_grid, tab_faculty, tab_room, tab_export = st.tabs([
        "🗓️ Weekly Master Grid", 
        "👨‍🏫 Faculty View", 
        "🏛️ Room Allocation View", 
        "📥 Export Schedule (CSV / PDF)"
    ])

    df = pd.DataFrame(entries)
    days_order = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday"]
    time_order = ["8AM", "9AM", "10AM", "11AM", "12PM", "1PM", "2PM", "3PM", "4PM", "5PM"]

    with tab_grid:
        st.subheader("Weekly Timetable Grid")
        theme.timetable_grid(
            entries,
            [d for d in days_order if d in set(df["day"])],
            [t for t in time_order if t in set(df["time_slot"])],
        )
        with st.expander("Raw table view"):
            # Build pivot table: rows = time_slot, columns = day
            # Cell text = Course (Room, Teacher)
            df["cell"] = df["course_id"] + " (" + df["room_id"] + ", " + df["teacher_name"] + ")"
            pivot_df = pd.pivot_table(
                df,
                index="time_slot",
                columns="day",
                values="cell",
                aggfunc=lambda x: "\n".join(x),
                fill_value="---"
            )
            # Reindex
            existing_days = [d for d in days_order if d in pivot_df.columns]
            existing_times = [t for t in time_order if t in pivot_df.index]
            pivot_df = pivot_df.reindex(index=existing_times, columns=existing_days)
            st.dataframe(pivot_df, width="stretch", height=450)

    with tab_faculty:
        st.subheader("Schedule by Faculty Member")
        teachers = sorted(df["teacher_name"].unique())
        selected_teacher = st.selectbox("Select Teacher:", teachers)
        df_teacher = df[df["teacher_name"] == selected_teacher][["day", "time_slot", "course_id", "room_id"]]
        st.dataframe(df_teacher, width="stretch")

    with tab_room:
        st.subheader("Schedule by Room / Laboratory")
        rooms = sorted(df["room_id"].unique())
        selected_room = st.selectbox("Select Room:", rooms)
        df_room = df[df["room_id"] == selected_room][["day", "time_slot", "course_id", "teacher_name"]]
        st.dataframe(df_room, width="stretch")

    with tab_export:
        st.subheader("Export Final University Timetable")
        col_csv, col_pdf = st.columns(2)

        with col_csv:
            csv_data = df.to_csv(index=False).encode("utf-8")
            st.download_button(
                label="📥 Download Timetable as CSV",
                data=csv_data,
                file_name="university_timetable.csv",
                mime="text/csv",
                width="stretch"
            )

        with col_pdf:
            if FPDF_AVAILABLE:
                pdf_bytes = generate_pdf(df)
                st.download_button(
                    label="📥 Download Timetable as PDF",
                    data=pdf_bytes,
                    file_name="university_timetable.pdf",
                    mime="application/pdf",
                    width="stretch"
                )
            else:
                st.warning("fpdf2 library not installed. Install with `pip install fpdf2` to enable PDF export.")


def generate_pdf(df: pd.DataFrame) -> bytes:
    """Generate a formatted PDF timetable document."""
    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 16)
    pdf.cell(0, 10, "Smart University Timetable Schedule", ln=True, align="C")
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(0, 8, "Generated by Timetable Constraint Compiler (Google OR-Tools CP-SAT)", ln=True, align="C")
    pdf.ln(5)

    pdf.set_font("Helvetica", "B", 10)
    pdf.set_fill_color(220, 230, 242)
    headers = ["Day", "Time Slot", "Course ID", "Teacher", "Room"]
    widths = [30, 25, 35, 55, 35]

    for header, width in zip(headers, widths):
        pdf.cell(width, 8, header, border=1, fill=True, align="C")
    pdf.ln()

    pdf.set_font("Helvetica", "", 9)
    for _, row in df.iterrows():
        pdf.cell(widths[0], 7, str(row.get("day", "")), border=1)
        pdf.cell(widths[1], 7, str(row.get("time_slot", "")), border=1)
        pdf.cell(widths[2], 7, str(row.get("course_id", "")), border=1)
        pdf.cell(widths[3], 7, str(row.get("teacher_name", "")), border=1)
        pdf.cell(widths[4], 7, str(row.get("room_id", "")), border=1)
        pdf.ln()

    return bytes(pdf.output())
